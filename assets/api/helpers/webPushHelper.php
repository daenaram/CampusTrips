<?php
/**
 * Dependency-free Web Push sender (no Composer needed).
 *
 * Implements the two pieces a push service requires:
 *  - VAPID (RFC 8292): an ES256-signed JWT proving the push came from this
 *    server, using a key pair generated once and kept in vapidKeys.php.
 *  - Message encryption (RFC 8291, "aes128gcm"): the payload is encrypted
 *    to the browser's own subscription keys, so the push service relaying
 *    it (Google, Mozilla, Apple, Microsoft) can never read reminder text.
 *
 * Needs the openssl and curl extensions, which WAMP enables by default.
 */

// Shown to push services as the contact for this sender. Apple in
// particular rejects pushes without a valid mailto: or https: subject —
// change this to a real team address before deploying.
const WEB_PUSH_SUBJECT = 'mailto:campustrips@example.com';

// Generated on first use, never committed (see .gitignore). A .php file
// rather than .json so Apache executes it instead of serving the private
// key to anyone who requests the URL.
const WEB_PUSH_KEYS_FILE = __DIR__ . '/../config/vapidKeys.php';

const WEB_PUSH_OPENSSL_CONFIG = __DIR__ . '/../config/openssl.cnf';

// Only these push services are ever contacted. Without this, a signed-in
// user could register any URL as their "endpoint" and make the server send
// requests to it (e.g. to machines on the internal network).
const WEB_PUSH_ALLOWED_HOST_SUFFIXES = [
    'fcm.googleapis.com',        // Chrome, Edge (Chromium), Opera, Brave, Samsung Internet
    'push.services.mozilla.com', // Firefox
    'notify.windows.com',        // Legacy Edge / Windows
    'push.apple.com',            // Safari (macOS 13+, iOS 16.4+ home-screen apps)
];

function base64UrlEncode(string $data): string
{
    return rtrim(strtr(base64_encode($data), '+/', '-_'), '=');
}

function base64UrlDecode(string $data): string
{
    return (string) base64_decode(strtr($data, '-_', '+/'), true);
}

function webPushIsAllowedEndpoint(string $endpoint): bool
{
    $parts = parse_url($endpoint);
    if (!$parts || ($parts['scheme'] ?? '') !== 'https' || empty($parts['host'])) {
        return false;
    }

    $host = strtolower($parts['host']);
    foreach (WEB_PUSH_ALLOWED_HOST_SUFFIXES as $suffix) {
        if ($host === $suffix || str_ends_with($host, '.' . $suffix)) {
            return true;
        }
    }
    return false;
}

/** A fresh P-256 key pair, as [OpenSSLAsymmetricKey, 65-byte uncompressed public point]. */
function webPushNewKeyPair(): array
{
    $key = openssl_pkey_new([
        'curve_name'       => 'prime256v1',
        'private_key_type' => OPENSSL_KEYTYPE_EC,
        'config'           => WEB_PUSH_OPENSSL_CONFIG,
    ]);
    if ($key === false) {
        throw new RuntimeException('Unable to generate EC key: ' . openssl_error_string());
    }

    $details = openssl_pkey_get_details($key);
    $publicPoint = "\x04"
        . str_pad($details['ec']['x'], 32, "\0", STR_PAD_LEFT)
        . str_pad($details['ec']['y'], 32, "\0", STR_PAD_LEFT);

    return [$key, $publicPoint];
}

/** Wraps a raw 65-byte P-256 point in a PEM public key OpenSSL can load. */
function webPushPublicPointToPem(string $point): string
{
    // DER prefix for SubjectPublicKeyInfo { id-ecPublicKey, prime256v1 }
    $der = hex2bin('3059301306072a8648ce3d020106082a8648ce3d030107034200') . $point;
    return "-----BEGIN PUBLIC KEY-----\n" . chunk_split(base64_encode($der), 64, "\n") . "-----END PUBLIC KEY-----\n";
}

/** Returns ['publicKey' => base64url, 'privateKeyPem' => PEM], generating them on first use. */
function webPushVapidKeys(): array
{
    static $keys = null;
    if ($keys !== null) {
        return $keys;
    }

    if (is_file(WEB_PUSH_KEYS_FILE)) {
        $keys = require WEB_PUSH_KEYS_FILE;
        return $keys;
    }

    [$key, $publicPoint] = webPushNewKeyPair();
    openssl_pkey_export($key, $privateKeyPem, null, ['config' => WEB_PUSH_OPENSSL_CONFIG]);

    $keys = [
        'publicKey'     => base64UrlEncode($publicPoint),
        'privateKeyPem' => $privateKeyPem,
    ];

    $contents = "<?php\n// Generated by webPushHelper.php. Keep private — do not commit.\n"
        . "// Deleting this file invalidates every existing push subscription.\n"
        . 'return ' . var_export($keys, true) . ";\n";
    if (file_put_contents(WEB_PUSH_KEYS_FILE, $contents, LOCK_EX) === false) {
        throw new RuntimeException('Unable to write ' . WEB_PUSH_KEYS_FILE);
    }

    return $keys;
}

/** Converts OpenSSL's DER-encoded ECDSA signature into the raw r||s form JWT ES256 expects. */
function webPushDerToRawSignature(string $der): string
{
    $offset = 2; // SEQUENCE tag + length (always short form for P-256)
    $raw = '';
    for ($i = 0; $i < 2; $i++) {
        $length = ord($der[$offset + 1]);
        $integer = substr($der, $offset + 2, $length);
        $raw .= str_pad(ltrim($integer, "\0"), 32, "\0", STR_PAD_LEFT);
        $offset += 2 + $length;
    }
    return $raw;
}

function webPushVapidHeader(string $endpoint): string
{
    $keys = webPushVapidKeys();
    $parts = parse_url($endpoint);

    $header = base64UrlEncode(json_encode(['typ' => 'JWT', 'alg' => 'ES256']));
    $claims = base64UrlEncode(json_encode([
        'aud' => $parts['scheme'] . '://' . $parts['host'],
        'exp' => time() + 12 * 3600,
        'sub' => WEB_PUSH_SUBJECT,
    ]));

    $signingInput = $header . '.' . $claims;
    if (!openssl_sign($signingInput, $derSignature, $keys['privateKeyPem'], OPENSSL_ALGO_SHA256)) {
        throw new RuntimeException('Unable to sign VAPID token: ' . openssl_error_string());
    }
    $jwt = $signingInput . '.' . base64UrlEncode(webPushDerToRawSignature($derSignature));

    return 'vapid t=' . $jwt . ', k=' . $keys['publicKey'];
}

/** Encrypts $payload for one subscription per RFC 8291 and returns the aes128gcm request body. */
function webPushEncrypt(string $payload, string $userPublicKey, string $userAuthSecret): string
{
    [$localKey, $localPublicPoint] = webPushNewKeyPair();

    $sharedSecret = openssl_pkey_derive(webPushPublicPointToPem($userPublicKey), $localKey, 32);
    if ($sharedSecret === false) {
        throw new RuntimeException('Unable to derive ECDH secret: ' . openssl_error_string());
    }

    $ikm = hash_hkdf('sha256', $sharedSecret, 32, "WebPush: info\0" . $userPublicKey . $localPublicPoint, $userAuthSecret);

    $salt = random_bytes(16);
    $contentKey = hash_hkdf('sha256', $ikm, 16, "Content-Encoding: aes128gcm\0", $salt);
    $nonce = hash_hkdf('sha256', $ikm, 12, "Content-Encoding: nonce\0", $salt);

    // 0x02 marks this as the final (and only) record.
    $ciphertext = openssl_encrypt($payload . "\x02", 'aes-128-gcm', $contentKey, OPENSSL_RAW_DATA, $nonce, $tag);

    $recordSize = 4096;
    $header = $salt . pack('N', $recordSize) . chr(strlen($localPublicPoint)) . $localPublicPoint;

    return $header . $ciphertext . $tag;
}

/**
 * Sends one push message.
 *
 * @param array $subscription ['endpoint' => ..., 'p256dh' => base64url, 'auth' => base64url]
 * @param array $message      JSON-encodable payload read by sw.js ('title', 'body', 'url', 'tag')
 * @return array ['ok' => bool, 'expired' => bool, 'status' => int, 'error' => string]
 */
function webPushSend(array $subscription, array $message): array
{
    $endpoint = $subscription['endpoint'];
    if (!webPushIsAllowedEndpoint($endpoint)) {
        return ['ok' => false, 'expired' => true, 'status' => 0, 'error' => 'Endpoint is not a recognised push service'];
    }

    $userPublicKey = base64UrlDecode($subscription['p256dh']);
    $userAuthSecret = base64UrlDecode($subscription['auth']);
    if (strlen($userPublicKey) !== 65 || strlen($userAuthSecret) !== 16) {
        return ['ok' => false, 'expired' => true, 'status' => 0, 'error' => 'Malformed subscription keys'];
    }

    $body = webPushEncrypt(json_encode($message), $userPublicKey, $userAuthSecret);

    $curl = curl_init($endpoint);
    curl_setopt_array($curl, [
        CURLOPT_POST           => true,
        CURLOPT_POSTFIELDS     => $body,
        CURLOPT_RETURNTRANSFER => true,
        CURLOPT_TIMEOUT        => 15,
        CURLOPT_HTTPHEADER     => [
            'Authorization: ' . webPushVapidHeader($endpoint),
            'Content-Encoding: aes128gcm',
            'Content-Type: application/octet-stream',
            'TTL: 86400', // keep for a day if the device is offline
            'Urgency: high',
        ],
    ]);
    // WAMP's PHP has no CA bundle configured; trust the Windows certificate
    // store instead of turning verification off.
    if (defined('CURLSSLOPT_NATIVE_CA') && PHP_OS_FAMILY === 'Windows') {
        curl_setopt($curl, CURLOPT_SSL_OPTIONS, CURLSSLOPT_NATIVE_CA);
    }

    $response = curl_exec($curl);
    $status = (int) curl_getinfo($curl, CURLINFO_HTTP_CODE);
    $curlError = curl_error($curl);
    curl_close($curl);

    return [
        'ok'      => $status >= 200 && $status < 300,
        // 404/410: the browser unsubscribed or the subscription expired.
        'expired' => $status === 404 || $status === 410,
        'status'  => $status,
        'error'   => $curlError !== '' ? $curlError : (is_string($response) ? $response : ''),
    ];
}

/**
 * Sends a message to every device a user has enabled push on, removing
 * subscriptions the push service reports as gone.
 *
 * @return int Number of devices the message was delivered to.
 */
function sendPushToUser(PDO $pdo, int $userId, array $message): int
{
    $stmt = $pdo->prepare("SELECT id, endpoint, p256dh, auth FROM push_subscriptions WHERE user_id = ?");
    $stmt->execute([$userId]);

    $delivered = 0;
    foreach ($stmt->fetchAll(PDO::FETCH_ASSOC) as $subscription) {
        try {
            $result = webPushSend($subscription, $message);
        } catch (Throwable $e) {
            error_log('Web push error: ' . $e->getMessage());
            continue;
        }

        if ($result['ok']) {
            $delivered++;
        } elseif ($result['expired']) {
            $pdo->prepare("DELETE FROM push_subscriptions WHERE id = ?")->execute([$subscription['id']]);
        } else {
            error_log("Web push failed ({$result['status']}): {$result['error']}");
        }
    }

    return $delivered;
}
